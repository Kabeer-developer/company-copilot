from bson import ObjectId
from fastapi import APIRouter, Depends, HTTPException, Query, Request, Response, status
from pymongo.database import Database

from app.core.config import CONVERSATION_HISTORY_LIMIT
from app.models.user import UserRole
from app.routes.auth import get_current_user, get_database
from app.schemas.chat import ChatRequest
from app.schemas.conversation import (
    ConversationDetail,
    ConversationExchangeResponse,
    ConversationListResponse,
    ConversationSummary,
)
from app.services.answer_service import answer_question
from app.services.conversation_service import (
    ConversationNotFoundError,
    ConversationPersistenceError,
    InvalidConversationIdError,
    add_assistant_message,
    add_user_message,
    create_conversation,
    delete_conversation,
    ensure_conversation_indexes,
    get_conversation,
    get_conversation_detail,
    list_conversations,
    load_recent_messages,
    update_conversation_activity,
)
from app.services.embedding_service import EmbeddingModelLoadError
from app.services.llm_service import LLMConfigurationError, LLMProviderError, LLMTimeoutError
from app.services.vector_search_service import QueryEmbeddingError, VectorSearchUnavailableError


router = APIRouter()


def get_conversation_database(
    request: Request,
    database: Database = Depends(get_database),
) -> Database:
    if not getattr(request.app.state, "conversation_indexes_ready", False):
        try:
            ensure_conversation_indexes(database)
        except ConversationPersistenceError as exc:
            raise HTTPException(
                status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
                detail="Conversation storage is temporarily unavailable.",
            ) from exc
        request.app.state.conversation_indexes_ready = True
    return database


def _raise_answer_error(exc: Exception) -> None:
    if isinstance(exc, (QueryEmbeddingError, EmbeddingModelLoadError)):
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="Document retrieval is unavailable. Check the embedding model configuration.",
        ) from exc
    if isinstance(exc, VectorSearchUnavailableError):
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="Document retrieval is temporarily unavailable.",
        ) from exc
    if isinstance(exc, LLMConfigurationError):
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="Answer generation is not configured. Check the server configuration.",
        ) from exc
    if isinstance(exc, LLMTimeoutError):
        raise HTTPException(
            status_code=status.HTTP_504_GATEWAY_TIMEOUT,
            detail="The answer generation request timed out.",
        ) from exc
    if isinstance(exc, LLMProviderError):
        raise HTTPException(
            status_code=status.HTTP_502_BAD_GATEWAY,
            detail="The answer could not be generated by the LLM provider.",
        ) from exc


@router.post("", response_model=ConversationSummary, status_code=status.HTTP_201_CREATED)
def create_user_conversation(
    current_user: dict = Depends(get_current_user),
    database: Database = Depends(get_conversation_database),
) -> dict:
    try:
        return create_conversation(database["conversations"], current_user)
    except ConversationPersistenceError as exc:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="The conversation could not be created.",
        ) from exc


@router.get("", response_model=ConversationListResponse)
def read_conversations(
    page: int = Query(default=1, ge=1),
    page_size: int = Query(default=20, ge=1, le=100),
    current_user: dict = Depends(get_current_user),
    database: Database = Depends(get_conversation_database),
) -> dict:
    try:
        return list_conversations(
            database["conversations"],
            current_user,
            page=page,
            page_size=page_size,
        )
    except ConversationPersistenceError as exc:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="Conversation storage is temporarily unavailable.",
        ) from exc


@router.get("/{conversation_id}", response_model=ConversationDetail)
def read_conversation(
    conversation_id: str,
    current_user: dict = Depends(get_current_user),
    database: Database = Depends(get_conversation_database),
) -> dict:
    try:
        return get_conversation_detail(
            database["conversations"],
            database["messages"],
            conversation_id,
            current_user,
        )
    except InvalidConversationIdError as exc:
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail="Invalid conversation ID") from exc
    except ConversationNotFoundError as exc:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Conversation not found") from exc
    except ConversationPersistenceError as exc:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="Conversation storage is temporarily unavailable.",
        ) from exc


@router.post("/{conversation_id}/messages", response_model=ConversationExchangeResponse)
def send_conversation_message(
    conversation_id: str,
    request: ChatRequest,
    current_user: dict = Depends(get_current_user),
    database: Database = Depends(get_conversation_database),
) -> dict:
    conversations = database["conversations"]
    messages = database["messages"]
    try:
        conversation = get_conversation(conversations, conversation_id, current_user)
        object_id = conversation["_id"]
        user_message = add_user_message(
            messages,
            conversation_id=object_id,
            current_user=current_user,
            content=request.query,
        )
        update_conversation_activity(
            conversations,
            conversation_id=object_id,
            current_user=current_user,
            first_question=request.query,
        )
        history = load_recent_messages(
            messages,
            conversation_id=object_id,
            current_user=current_user,
            limit=CONVERSATION_HISTORY_LIMIT,
            exclude_message_id=user_message["id"],
        )
    except InvalidConversationIdError as exc:
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail="Invalid conversation ID") from exc
    except ConversationNotFoundError as exc:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Conversation not found") from exc
    except ConversationPersistenceError as exc:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="The conversation could not be saved completely.",
        ) from exc

    try:
        answer = answer_question(
            database["document_chunks"],
            query=request.query,
            current_user=current_user,
            is_admin=current_user.get("role") == UserRole.ADMIN.value,
            history=history,
        )
    except (QueryEmbeddingError, EmbeddingModelLoadError, VectorSearchUnavailableError,
            LLMConfigurationError, LLMTimeoutError, LLMProviderError) as exc:
        _raise_answer_error(exc)

    try:
        assistant_message = add_assistant_message(
            messages,
            conversation_id=object_id,
            current_user=current_user,
            content=answer["answer"],
            sources=answer["sources"],
        )
    except ConversationPersistenceError as exc:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="The answer was generated, but the conversation exchange could not be saved completely.",
        ) from exc

    return {
        "conversation_id": str(object_id),
        "user_message": user_message,
        "assistant_message": assistant_message,
    }


@router.delete("/{conversation_id}", status_code=status.HTTP_204_NO_CONTENT)
def remove_conversation(
    conversation_id: str,
    current_user: dict = Depends(get_current_user),
    database: Database = Depends(get_conversation_database),
) -> Response:
    try:
        delete_conversation(
            database["conversations"],
            database["messages"],
            conversation_id,
            current_user,
        )
    except InvalidConversationIdError as exc:
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail="Invalid conversation ID") from exc
    except ConversationNotFoundError as exc:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Conversation not found") from exc
    except ConversationPersistenceError as exc:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="The conversation could not be deleted completely.",
        ) from exc
    return Response(status_code=status.HTTP_204_NO_CONTENT)
